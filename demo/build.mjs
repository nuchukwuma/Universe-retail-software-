// Bundles the real server code for the browser demo (see api/entry.js).
// Files that need a computer (data files, pictures on disk, backups,
// sending to Telegram) are swapped for browser versions, and the few Node
// modules the server uses get small stand-ins.
//   node demo/build.mjs  ->  client/src/demo/demoServer.gen.js
import { build } from '../client/node_modules/esbuild/lib/main.js';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const server = path.join(root, 'server');

// Server file -> browser version.
const REPLACE = {
  [path.join(server, 'db/store.js')]: path.join(here, 'api/replacements/store.js'),
  [path.join(server, 'utils/images.js')]: path.join(here, 'api/replacements/images.js'),
  [path.join(server, 'utils/backup.js')]: path.join(here, 'api/replacements/backup.js'),
  [path.join(server, 'utils/paths.js')]: path.join(here, 'api/replacements/paths.js'),
  [path.join(server, 'utils/postJson.js')]: path.join(here, 'api/replacements/postJson.js'),
};

// Node module -> stand-in (a file, or a named export of shims/node.js).
const MODULES = {
  express: path.join(here, 'api/shims/express.js'),
  jsonwebtoken: path.join(here, 'api/shims/jsonwebtoken.js'),
  bcryptjs: path.join(here, 'api/shims/bcryptjs.js'),
  cors: 'unavailable',
  dotenv: 'unavailable',
  crypto: 'crypto',
  path: 'path',
  os: 'os',
  fs: 'unavailable',
  http: 'unavailable',
  https: 'unavailable',
  readline: 'unavailable',
  events: 'unavailable',
};

const swapPlugin = {
  name: 'hordedesk-demo',
  setup(b) {
    b.onResolve({ filter: /.*/ }, async (args) => {
      const bare = args.path.replace(/^node:/, '');
      if (MODULES[bare]) {
        const target = MODULES[bare];
        if (target.endsWith('.js')) return { path: target };
        return { path: target, namespace: 'node-shim' };
      }
      if (args.path.startsWith('.') && args.resolveDir) {
        let full = path.resolve(args.resolveDir, args.path);
        if (!full.endsWith('.js')) full += '.js';
        if (REPLACE[full]) return { path: REPLACE[full] };
      }
      return undefined;
    });
    b.onLoad({ filter: /.*/, namespace: 'node-shim' }, (args) => ({
      contents: `module.exports = require(${JSON.stringify(path.join(here, 'api/shims/node.js'))})[${JSON.stringify(args.path)}];`,
      resolveDir: here,
      loader: 'js',
    }));
  },
};

await build({
  entryPoints: [path.join(here, 'api/entry.js')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  outfile: path.join(root, 'client/src/demo/demoServer.gen.js'),
  nodePaths: [path.join(server, 'node_modules')],
  plugins: [swapPlugin],
  banner: {
    js: [
      '// Generated by demo/build.mjs from the server code. Do not edit.',
      '/* eslint-disable */',
      "var process = globalThis.process || (globalThis.process = { env: { NODE_ENV: 'production' }, pid: 1, platform: 'browser', version: 'v16.17.1', versions: {}, on() {}, nextTick: (fn, ...a) => Promise.resolve().then(() => fn(...a)) });",
    ].join('\n'),
  },
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
  legalComments: 'none',
});
console.log('Demo server bundled: client/src/demo/demoServer.gen.js');
